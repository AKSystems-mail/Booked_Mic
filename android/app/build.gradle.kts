import java.util.Properties

fun loadKeystoreProperties(): Properties {
    val properties = Properties()
    val keystoreFile = rootProject.file("key.properties")
    if (keystoreFile.exists()) {
        properties.load(keystoreFile.inputStream())
    }
    return properties
}

